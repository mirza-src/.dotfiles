# profile: switch named profiles by pointing a fixed link at one of several
# sources (an SSH agent socket, a Claude settings file, ...). Consumers read
# the link, so a switch applies to everything started afterwards.
#
#   profile                          every switch and its active option
#   profile SWITCH                   its options, the active one marked
#   profile SWITCH OPTION            switch: point the link at OPTION
#   profile SWITCH OPTION -- CMD...  run CMD under OPTION only (sets the
#                                    switch's environment variable), the
#                                    link stays as it is
#   profile --init                   link each switch's default where it
#                                    changed (another specialisation) or the
#                                    link is missing or broken (activation,
#                                    shell startup)
#
# The switches come from $PROFILE_SWITCH_CONFIG (JSON, generated by
# modules/home-manager/profile-switch). Sources may contain shell expansions
# such as $XDG_RUNTIME_DIR, expanded here.

config=$PROFILE_SWITCH_CONFIG
# Per switch, the default --init last applied.
state_dir=$HOME/.local/state/profile-switch

switches() { jq -r 'keys[]' "$config"; }
field() { jq -r --arg s "$1" ".[\$s].$2 // empty" "$config"; }
options() { jq -r --arg s "$1" '.[$s].options | keys[]' "$config"; }
expand() { eval "printf '%s' \"$1\""; }
source_of() { # switch option
  local raw
  raw=$(jq -r --arg s "$1" --arg o "$2" '.[$s].options[$o] // empty' "$config")
  if [[ -n $raw ]]; then expand "$raw"; fi
}
usable() { # switch path
  if [[ $(field "$1" kind) == socket ]]; then [[ -S $2 ]]; else [[ -e $2 ]]; fi
}
active() { # switch -> option name, or "(none)"
  local link target option
  link=$(expand "$(field "$1" link)")
  target=$(readlink "$link" 2>/dev/null) || {
    echo "(none)"
    return
  }
  for option in $(options "$1"); do
    if [[ $(source_of "$1" "$option") == "$target" ]]; then
      if usable "$1" "$target"; then echo "$option"; else echo "$option (not available)"; fi
      return
    fi
  done
  echo "(other: $target)"
}
link_to() { # switch option
  local link
  link=$(expand "$(field "$1" link)")
  mkdir -p "$(dirname "$link")"
  ln -sfn "$(source_of "$1" "$2")" "$link"
}

case ${1:-} in
"")
  for s in $(switches); do
    printf '%-10s %s\n' "$s" "$(active "$s")"
  done
  exit 0
  ;;
--init)
  for s in $(switches); do
    default=$(field "$s" default)
    [[ -n $default ]] || continue
    link=$(expand "$(field "$s" link)")
    usable "$s" "$(source_of "$s" "$default")" || continue
    # Apply a default that changed (e.g. another home-manager
    # specialisation); otherwise keep a working link (the last switch) and
    # only replace a missing or broken one. A default whose source isn't
    # usable yet (agent not running) is applied by a later --init.
    state=$state_dir/$s
    if [[ $(cat "$state" 2>/dev/null) != "$default" ]]; then
      link_to "$s" "$default"
      mkdir -p "$state_dir"
      printf '%s' "$default" >"$state"
    elif ! usable "$s" "$link"; then
      link_to "$s" "$default"
    fi
  done
  exit 0
  ;;
esac

switch=$1
if ! switches | grep -qxF -- "$switch"; then
  echo "profile: no switch '$switch' (have: $(switches | tr '\n' ' '))" >&2
  exit 2
fi

if (($# == 1)); then
  current=$(active "$switch")
  for option in $(options "$switch"); do
    if [[ $option == "$current" ]]; then mark="*"; else mark=" "; fi
    printf '%s %-12s %s\n' "$mark" "$option" "$(source_of "$switch" "$option")"
  done
  exit 0
fi

option=$2
source=$(source_of "$switch" "$option")
if [[ -z $source ]]; then
  echo "profile: $switch has no option '$option' (have: $(options "$switch" | tr '\n' ' '))" >&2
  exit 2
fi
if ! usable "$switch" "$source"; then
  echo "profile: $switch/$option is not available: $source" >&2
  exit 1
fi

if (($# == 2)); then
  link_to "$switch" "$option"
  echo "✓ $switch: $option"
  exit 0
fi

if [[ $3 != -- ]] || (($# < 4)); then
  echo "usage: profile $switch $option -- COMMAND [ARGS...]" >&2
  exit 2
fi
shift 3
env=$(field "$switch" env)
if [[ -z $env ]]; then
  echo "profile: $switch has no environment variable to run a command under" >&2
  exit 2
fi
export "$env=$source"
exec "$@"
